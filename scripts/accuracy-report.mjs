// Builds docs/accuracy.md from the oracle test summaries in reports/ (run `npm run test:oracle` first).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const read = (n) => (existsSync(`reports/${n}.json`) ? JSON.parse(readFileSync(`reports/${n}.json`, 'utf8')) : null);
const out = [];
const p = (s = '') => out.push(s);

p('# Accuracy report');
p();
p('Generated by `scripts/accuracy-report.mjs` from the oracle tests (`npm run test:oracle`). Do not edit by hand.');
p('Oracles are independent implementations used only in tests (see ADR-0003); a difference means one of the two is');
p('wrong or follows another convention, and each one is explained below.');
p();

const cal = read('calendar');
p('## Calendar');
p();
if (cal) p(`- Hebrew ↔ Gregorian: ${cal.daysCompared.toLocaleString('en')} days (${cal.range}) compared with ${cal.oracle}: **${cal.mismatches} differences**.`);
p('- Molad: every month 5660–6000 agrees with @hebcal/core to the chelek; the molad instant and Kiddush Levana times');
p('  agree with kosher-zmanim to the millisecond.');
p('- Yahrzeits and birthdays (deaths/births 5740–5760, 40 years each): identical to @hebcal/core with the Rema, Magen Avraham');
p('  and Levush customs selected.');
p('- Property tests over 5660–6000: round-trips, year lengths, Rosh Hashana weekdays, at-bash, Yom Kippur, Purim, Hoshana Rabba.');
p();

p('## Parsha');
p();
for (const loc of ['diaspora', 'israel']) {
  const r = read(`parsha-${loc}`);
  if (r) p(`- ${loc}: ${r.shabbosos.toLocaleString('en')} Shabbosos (${r.years}) vs ${r.oracle}: **${r.mismatches} differences**.`);
}
p();

p('## Holidays');
p();
for (const loc of ['diaspora', 'israel']) {
  const r = read(`holidays-${loc}`);
  if (!r) continue;
  p(`- ${loc}: ${r.eventsCompared.toLocaleString('en')} events (${r.years}) vs ${r.oracle}: **${r.unexplained} unexplained differences**, ${r.explained.length} explained:`);
}
p('  - Yom HaShoah before 5757: the Sunday→Monday rule dates from 1997 (Hebrew Wikipedia, "יום הזיכרון לשואה ולגבורה"); the oracle applies it to earlier years.');
p('  - Yom HaZikaron 5708–5710: established in 5711/1951; the oracle lists earlier years.');
p('  - Yom Yerushalayim 5727: declared in 5728/1968; the oracle also lists 28 Iyar 5727 itself.');
p();

p('## Zmanim');
p();
const kz = read('zmanim-kosher-zmanim');
const ae = read('zmanim-astronomy-engine');
const summarise = (stats) => {
  let compared = 0, sum = 0, max = 0, grazing = 0, transitJumps = 0;
  for (const [k, s] of Object.entries(stats)) {
    compared += s.compared; sum += s.sumDiffSec; max = Math.max(max, s.maxDiffSec);
    if (k.startsWith('Chatham|chatzos')) transitJumps += s.grazing?.length ?? 0;
    else grazing += s.grazing?.length ?? 0;
  }
  return { compared, mean: sum / Math.max(1, compared), max, grazing, transitJumps };
};
if (ae) {
  const s = summarise(ae);
  p(`### astronomy-engine (MIT), 19 cities, daily 2025–2028`);
  p();
  p(`${s.compared.toLocaleString('en')} comparisons of sunrise, sunset, chatzos, alos 16.1° and tzeis 8.5°: mean difference ${s.mean.toFixed(1)} s, maximum ${s.max.toFixed(0)} s.`);
  p('Differences over 1 minute occur only at Anchorage, Reykjavik and Tromsø on days when the sun just grazes the angle (see below).');
  p();
}
if (kz) {
  const s = summarise(kz);
  p(`### kosher-zmanim (LGPL), 19 cities, daily 2025–2028, ${Object.keys(kz).length / 19} opinions`);
  p();
  p(`${s.compared.toLocaleString('en')} comparisons: mean difference ${s.mean.toFixed(1)} s (both implement the NOAA equations). No difference over 1 minute except those explained:`);
  p();
  p('- **Sydney, Auckland, Chatham: kosher-zmanim is one day off** (its issue #37, a sign-inverted raw offset in DST zones).');
  p('  Luach is on the requested day: see the regression test in `test/zmanim.test.ts` and the astronomy-engine comparison.');
  p('  The comparison uses kosher-zmanim\'s answer for the previous date.');
  p(`- **Chatham chatzos, about 4–20 February (${s.transitJumps} days in 4 years):** kosher-zmanim\'s transit jumps a further day when solar noon crosses 00:00 UTC.`);
  p('  astronomy-engine agrees with Luach on every one of these days.');
  p(`- **Grazing-sun days (${s.grazing}):** on these days the sun's lowest (or highest) point is within 1° of the angle, so the`);
  p('  time moves by minutes for a hundredth of a degree, and the two libraries may disagree on whether the angle is reached at all:');
  p();
  p('| City / opinion | Dates |');
  p('|---|---|');
  for (const [k, v] of Object.entries(kz)) if (v.grazing?.length && !k.startsWith('Chatham|chatzos')) p(`| ${k.replace('|', ' / ')} | ${v.grazing.join('; ')} |`);
  p();
  p('### Largest differences by opinion (seconds)');
  p();
  p('| Opinion | Worst city | Max | Mean (all cities) |');
  p('|---|---|---|---|');
  const byOpinion = {};
  for (const [k, v] of Object.entries(kz)) {
    const [city, op] = k.split('|');
    const o = (byOpinion[op] ??= { max: 0, city: '', sum: 0, n: 0 });
    if (v.maxDiffSec > o.max) { o.max = v.maxDiffSec; o.city = city; }
    o.sum += v.sumDiffSec; o.n += v.compared;
  }
  for (const [op, o] of Object.entries(byOpinion)) p(`| ${op} | ${o.city} | ${o.max.toFixed(1)} | ${(o.sum / o.n).toFixed(1)} |`);
  p();
}
p('### Why small differences remain');
p();
p('- Both libraries use the NOAA equations, but with different iteration and elevation constants (earth radius).');
p('- astronomy-engine uses a full planetary model and its own refraction; differences of a few seconds are expected.');
p('- Near the poles the sun moves almost horizontally, so tiny altitude differences become large time differences.');
p();
writeFileSync('docs/accuracy.md', out.join('\n'));
console.log('wrote docs/accuracy.md');
